/**
 * Blocks whose prefix points at the wrong page.
 *
 * `misc_` is the one prefix that is not an area: misc.js is where blocks
 * that belong to no single category ended up, so they have to be said
 * one by one.
 */
const EXCEPTIONS = {
  misc_addFile: "Blocks/Components/file-display",
  misc_createcontainer: "Blocks/Components/layout",
  misc_everyone: "Blocks/Components",
  misc_int_edit_mutator: "Interactions",
  misc_int_id: "Interactions",
  misc_int_reply_mutator: "Interactions",
  misc_permissionChannel: "Blocks/Servers/channels#permissions",
  misc_messageSent: "Blocks/Servers/channels#sending-a-message",
};

/** Flattened once, on first use: block type → `page#section`. */
let pages = null;

function table() {
  if (pages) return pages;

  pages = { ...EXCEPTIONS };

  for (const [page, blocks] of Object.entries(PAGE_BLOCKS))
    for (const [type, anchor] of blocks)
      if (!pages[type]) pages[type] = anchor ? `${page}#${anchor}` : page;

  return pages;
}

/**
 * The docs address for a block, or null if nothing sensible fits.
 *
 * Null rather than the docs home page on purpose: Blockly hides the
 * "Help" item on a block with no help URL, and a Help item that lands on
 * an index is worse than no Help item at all.
 *
 * @param {string} type a Blockly block type, e.g. `"channel_send"`
 * @returns {string|null}
 */
export function blockDocsUrl(type) {
  if (!type) return null;

  const exact = table()[type];
  if (exact) return docsUrl(exact);

  const prefix = PREFIX_PAGES[String(type).split("_")[0]];
  return prefix ? docsUrl(prefix) : null;
}
