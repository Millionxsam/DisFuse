/* =====================================================================
   Where each block is documented
   ---------------------------------------------------------------------
   Every block in the toolbox has a "Help" item in its right-click menu,
   and this is what it opens: the docs page for the category that block
   belongs to, pointed at the section that talks about the block itself
   where the docs have one.

   The table is grouped by docs page, and within a page each entry is
   `[block type, section anchor]`. It was built by reading the docs — the
   pages illustrate their blocks with screenshots named after the block
   type, so a block's section is the heading above its screenshot — and
   it is applied by blocks/lib/setHelpUrls.js.

   A block that is not listed falls back to its prefix: anything starting
   `channel_` lands on the Channels page even if it is newer than this
   table. That is why PREFIX_PAGES exists rather than only this map — a
   block added tomorrow still gets useful help.
   ===================================================================== */

